const SAFETY = [
  'Атыс бағытында ешкім тұрмайды.',
  'Сақаны адамға қарай лақтыруға болмайды.',
  'Асықтарды тек мұғалімнің белгісінен кейін жинаймыз.',
];

interface Spec {
  num: number;
  id: string;
  title: string;
  ru: string;
  goal: string;
  rule: string;
  throws: number;
  scoring: Scoring;
  setups: TargetSetup[];
  groups?: { label: string; from: number; to: number }[];
  guideDefault: boolean;
  power: number;
  demoSteps: { title: string; text: string }[];
  quiz: QuizQ[];
  task: string;
  inventory: string[];
  conditions: string[];
  steps: string[];
  success: string;
}

const trio = (x: number, z: number, gap = 1.1, extra: Partial<TargetSetup> = {}): TargetSetup => ({
  target: { x, z }, neighbors: [{ x: x - gap, z }, { x: x + gap, z }], ...extra,
});
const ctl = (x: number, z: number, gap = 1.1): TargetSetup => trio(x, z, gap, { limit: LIMIT });
const knock = (x: number, z: number, others: { x: number; z: number }[]): TargetSetup => ({
  target: { x, z }, neighbors: others, ring: KNOCK_R,
});

function build(s: Spec): LessonDef {
  const first = s.setups[0];
  const knockMode = s.scoring === 'knock';
  return {
    id: s.id,
    num: s.num,
    title: s.title,
    ru: s.ru,
    goal: s.goal,
    rule: s.rule,
    throws: s.throws,
    scoring: s.scoring,
    setups: s.setups,
    groups: s.groups,
    guideDefault: s.guideDefault,
    demo: {
      target: first.target,
      others: first.neighbors,
      power: s.power,
      limit: first.limit,
      ring: first.ring,
      knock: knockMode,
    },
    demoSteps: s.demoSteps,
    quiz: s.quiz,
    card: {
      title: s.title,
      goal: s.goal,
      task: s.task,
      inventory: s.inventory,
      conditions: s.conditions,
      attempts: s.throws,
      safety: SAFETY,
      steps: s.steps,
      success: s.success,
      realFields: s.groups
        ? s.groups.map(g => ({ label: g.label, total: g.to - g.from }))
        : [{ label: 'Тиген лақтырыс', total: s.throws }],
      points: knockMode,
    },
  };
}

